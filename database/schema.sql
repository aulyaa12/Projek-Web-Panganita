-- Urutan eksekusi:
-- 1. Jalankan script ini di Supabase SQL Editor pada database / project target.
-- 2. Lanjutkan dengan mengeksekusi seed.sql untuk data awal master bahan pangan,
--    standar AKG Permenkes No. 28/2019, dan parameter rumus panen.
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- EXTENSION
-- ----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ----------------------------------------------------------------------------
-- 1. PROFIL KELUARGA (profil_keluarga)
-- Menyimpan identitas ibu, domisili, kondisi ibu hamil/menyusui, dan
-- jumlah anggota keluarga berdasarkan rentang usia 1.000 HPK.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profil_keluarga (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE
        REFERENCES auth.users(id) ON DELETE CASCADE,

    nama_ibu        TEXT NOT NULL,
    provinsi        TEXT,
    kabupaten_kota  TEXT,

    -- Status kondisi ibu
    ibu_hamil         BOOLEAN NOT NULL DEFAULT FALSE,
    trimester_hamil   SMALLINT,                 -- 1, 2, atau 3 (wajib jika ibu_hamil = TRUE)
    ibu_menyusui      BOOLEAN NOT NULL DEFAULT FALSE,
    periode_menyusui  SMALLINT,                 -- 1 (0-6 bulan) atau 2 (7-12 bulan)

    -- Jumlah anggota keluarga per kelompok umur gizi (1.000 HPK & anak)
    jumlah_bayi_6_11     SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_bayi_6_11 >= 0),
    jumlah_anak_1_3      SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_anak_1_3 >= 0),
    jumlah_anak_4_6      SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_anak_4_6 >= 0),
    jumlah_anak_7_9      SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_anak_7_9 >= 0),
    jumlah_anak_l_10_12  SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_anak_l_10_12 >= 0),
    jumlah_anak_p_10_12  SMALLINT NOT NULL DEFAULT 0 CHECK (jumlah_anak_p_10_12 >= 0),

    dibuat_pada     TIMESTAMPTZ NOT NULL DEFAULT now(),
    diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_trimester CHECK (
        (ibu_hamil = TRUE  AND trimester_hamil IS NOT NULL AND trimester_hamil BETWEEN 1 AND 3)
        OR (ibu_hamil = FALSE AND trimester_hamil IS NULL)
    ),
    CONSTRAINT ck_periode_menyusui CHECK (
        (ibu_menyusui = TRUE  AND periode_menyusui IS NOT NULL AND periode_menyusui IN (1, 2))
        OR (ibu_menyusui = FALSE AND periode_menyusui IS NULL)
    )
);

-- ----------------------------------------------------------------------------
-- 2. KEBUTUHAN GIZI (kebutuhan_gizi)
-- Standar Angka Kecukupan Gizi (AKG) energi (kkal) & protein (gram) per hari.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.kebutuhan_gizi (
    kode TEXT PRIMARY KEY,
    nama TEXT NOT NULL,
    jenis TEXT NOT NULL
        CHECK (jenis IN ('dasar', 'tambahan_hamil', 'tambahan_menyusui')),
    untuk_perhitungan BOOLEAN NOT NULL DEFAULT TRUE,
    energi_kkal NUMERIC(8,2) NOT NULL CHECK (energi_kkal >= 0),
    protein_g   NUMERIC(8,2) NOT NULL CHECK (protein_g >= 0),
    sumber      TEXT NOT NULL DEFAULT 'Permenkes No. 28 Tahun 2019',

    CHECK (
        (jenis = 'dasar' AND kode NOT LIKE 'hamil\_%' AND kode NOT LIKE 'menyusui\_%')
        OR (jenis = 'tambahan_hamil' AND kode LIKE 'hamil\_%')
        OR (jenis = 'tambahan_menyusui' AND kode LIKE 'menyusui\_%')
    )
);

-- ----------------------------------------------------------------------------
-- 3. BAHAN PANGAN PEKARANGAN (bahan_pangan)
-- Master komoditas pangan lokal, kategori, BDD, nilai gizi TKPI, dan estimasi harga.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bahan_pangan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama          TEXT NOT NULL UNIQUE,
    nama_kelas_cv TEXT NOT NULL UNIQUE,          -- Label identifikasi Computer Vision (YOLO)
    kategori      TEXT NOT NULL
        CHECK (kategori IN ('lauk_hewani', 'sayur_buah', 'makanan_pokok')),
    kode_tkpi     TEXT,

    -- Berat Dapat Dimakan (BDD) dalam desimal (contoh: 0.800 = 80%)
    bdd NUMERIC(4,3) CHECK (bdd IS NULL OR (bdd > 0 AND bdd <= 1)),

    -- Kandungan gizi per 100 gram BDD
    energi_kkal_per_100g_bdd  NUMERIC(8,2) CHECK (energi_kkal_per_100g_bdd >= 0),
    protein_g_per_100g_bdd    NUMERIC(6,2) CHECK (protein_g_per_100g_bdd >= 0),
    lemak_g_per_100g_bdd      NUMERIC(6,2) CHECK (lemak_g_per_100g_bdd >= 0),
    serat_g_per_100g_bdd      NUMERIC(6,2) CHECK (serat_g_per_100g_bdd >= 0),
    kalsium_mg_per_100g_bdd   NUMERIC(8,2) CHECK (kalsium_mg_per_100g_bdd >= 0),
    vitamin_c_mg_per_100g_bdd NUMERIC(8,2) CHECK (vitamin_c_mg_per_100g_bdd >= 0),

    harga_umum_per_kg     NUMERIC(14,2) CHECK (harga_umum_per_kg IS NULL OR harga_umum_per_kg >= 0),
    harga_diperbarui_pada TIMESTAMPTZ
);

-- ----------------------------------------------------------------------------
-- 4. PENGATURAN RUMUS KALKULASI (pengaturan_rumus)
-- Parameter porsi gizi, hari cadangan default, dan pembagian panen vs jual.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pengaturan_rumus (
    versi             TEXT PRIMARY KEY,
    status_pengesahan TEXT NOT NULL DEFAULT 'draft'
        CHECK (status_pengesahan IN ('draft', 'disahkan')),
    disahkan_oleh     TEXT,
    berlaku_mulai     DATE NOT NULL,

    hari_cadangan_default SMALLINT NOT NULL CHECK (hari_cadangan_default > 0),
    pembulatan_kg         NUMERIC(6,3) NOT NULL CHECK (pembulatan_kg > 0),

    porsi_protein_lauk NUMERIC(4,3) NOT NULL CHECK (porsi_protein_lauk BETWEEN 0 AND 1),

    porsi_energi_pokok     NUMERIC(4,3) NOT NULL CHECK (porsi_energi_pokok BETWEEN 0 AND 1),
    porsi_pokok_dari_panen NUMERIC(4,3) NOT NULL CHECK (porsi_pokok_dari_panen BETWEEN 0 AND 1),

    porsi_sayur_buah_g_per_orang NUMERIC(8,2) NOT NULL CHECK (porsi_sayur_buah_g_per_orang >= 0),
    porsi_sayur_buah_dari_panen  NUMERIC(4,3) NOT NULL CHECK (porsi_sayur_buah_dari_panen BETWEEN 0 AND 1),

    batas_jual_seimbang NUMERIC(4,3) NOT NULL CHECK (batas_jual_seimbang BETWEEN 0 AND 1),
    persen_surplus_gizi NUMERIC(4,3) NOT NULL CHECK (persen_surplus_gizi BETWEEN 0 AND 1),

    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (status_pengesahan = 'draft' OR disahkan_oleh IS NOT NULL)
);

-- ----------------------------------------------------------------------------
-- 5. HASIL PANEN PEKARANGAN (panen)
-- Input hasil panen, metadata deteksi AI CV, serta path penyimpanan foto.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.panen (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_id INTEGER NOT NULL
        REFERENCES public.profil_keluarga(id) ON DELETE CASCADE,
    bahan_id  INTEGER NOT NULL
        REFERENCES public.bahan_pangan(id) ON DELETE RESTRICT,

    -- Foto hasil panen di Supabase Storage bucket 'hasil-panen'
    path_foto   TEXT UNIQUE,
    tipe_mime   TEXT CHECK (tipe_mime IS NULL OR tipe_mime IN ('image/jpeg', 'image/png', 'image/webp')),
    ukuran_byte INTEGER CHECK (ukuran_byte IS NULL OR (ukuran_byte > 0 AND ukuran_byte <= 10485760)),

    -- Metadata AI Computer Vision
    model_versi    TEXT,
    label_mentah   TEXT,
    skor_keyakinan NUMERIC(6,5) CHECK (skor_keyakinan IS NULL OR skor_keyakinan BETWEEN 0 AND 1),

    -- Input kuantitas panen
    berat_kg          NUMERIC(12,3) NOT NULL CHECK (berat_kg > 0),
    harga_jual_per_kg NUMERIC(14,2) NOT NULL CHECK (harga_jual_per_kg >= 0),

    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (path_foto IS NULL OR (tipe_mime IS NOT NULL AND ukuran_byte IS NOT NULL))
);

-- ----------------------------------------------------------------------------
-- 6. RIWAYAT KEPUTUSAN PANEN (riwayat_keputusan)
-- Snapshot keputusan alokasi panen: cadangan konsumsi keluarga vs porsi jual.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.riwayat_keputusan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_id INTEGER NOT NULL
        REFERENCES public.profil_keluarga(id) ON DELETE CASCADE,
    panen_id  INTEGER
        REFERENCES public.panen(id) ON DELETE SET NULL,
    versi_rumus TEXT NOT NULL
        REFERENCES public.pengaturan_rumus(versi),

    nama_bahan        TEXT NOT NULL,
    jumlah_orang      SMALLINT NOT NULL CHECK (jumlah_orang > 0),
    berat_panen_kg    NUMERIC(12,3) NOT NULL CHECK (berat_panen_kg > 0),
    harga_jual_per_kg NUMERIC(14,2) NOT NULL CHECK (harga_jual_per_kg >= 0),
    hari_disediakan   SMALLINT NOT NULL CHECK (hari_disediakan > 0),

    akg_energi_kkal       NUMERIC(10,2) NOT NULL CHECK (akg_energi_kkal >= 0),
    akg_protein_g         NUMERIC(10,2) NOT NULL CHECK (akg_protein_g >= 0),
    kebutuhan_cadangan_kg NUMERIC(12,3) NOT NULL CHECK (kebutuhan_cadangan_kg >= 0),
    kekurangan_kg         NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (kekurangan_kg >= 0),

    -- Opsi alternatif keputusan yang dipilih ibu
    keputusan TEXT NOT NULL
        CHECK (keputusan IN ('prioritas_uang', 'seimbang', 'prioritas_gizi')),
    berat_simpan_kg NUMERIC(12,3) NOT NULL CHECK (berat_simpan_kg >= 0),
    berat_jual_kg   NUMERIC(12,3) NOT NULL CHECK (berat_jual_kg >= 0),
    pendapatan_rp   NUMERIC(16,2) NOT NULL CHECK (pendapatan_rp >= 0),

    kontribusi_energi_persen  NUMERIC(6,2)  NOT NULL CHECK (kontribusi_energi_persen >= 0),
    kontribusi_protein_persen NUMERIC(6,2)  NOT NULL CHECK (kontribusi_protein_persen >= 0),
    sisa_energi_kkal          NUMERIC(10,2) NOT NULL CHECK (sisa_energi_kkal >= 0),
    sisa_protein_g            NUMERIC(10,2) NOT NULL CHECK (sisa_protein_g >= 0),

    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (ABS(berat_simpan_kg + berat_jual_kg - berat_panen_kg) < 0.001)
);

-- ----------------------------------------------------------------------------
-- 7. KODE OTP WHATSAPP (otp_codes)
-- Autentikasi pendaftaran/login via WhatsApp OTP (Fonnte API Gateway).
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.otp_codes (
    id          BIGSERIAL PRIMARY KEY,
    phone       VARCHAR(20) NOT NULL,
    code_hash   CHAR(64)    NOT NULL,            -- Hash SHA-256 kode OTP
    attempts    SMALLINT    NOT NULL DEFAULT 0,
    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 8. PERCAKAPAN CHATBOT BU NITA AI (percakapan)
-- Sesi konsultasi tanya jawab gizi keluarga berbasis RAG.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.percakapan (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    profil_id INTEGER NOT NULL
        REFERENCES public.profil_keluarga(id) ON DELETE CASCADE,
    judul TEXT CHECK (judul IS NULL OR char_length(judul) <= 120),
    diarsipkan BOOLEAN NOT NULL DEFAULT FALSE,
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now(),
    diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 9. PESAN CHAT (pesan_chat)
-- Detail pesan pengguna, asisten Bu Nita AI, dan referensi kutipan buku gizi.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pesan_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    percakapan_id UUID NOT NULL
        REFERENCES public.percakapan(id) ON DELETE CASCADE,
    peran TEXT NOT NULL
        CHECK (peran IN ('pengguna', 'asisten', 'sistem')),
    isi TEXT NOT NULL
        CHECK (char_length(isi) BETWEEN 1 AND 8000),
    sumber_rujukan JSONB,                        -- Sumber halaman buku panduan RAG
    model_versi TEXT,                            -- Gemini 2.5 Flash / fallback
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- INDEKS PERFORMA AKSES
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_profil_user           ON public.profil_keluarga(user_id);
CREATE INDEX IF NOT EXISTS idx_panen_profil          ON public.panen(profil_id);
CREATE INDEX IF NOT EXISTS idx_panen_bahan           ON public.panen(bahan_id);
CREATE INDEX IF NOT EXISTS idx_riwayat_profil        ON public.riwayat_keputusan(profil_id, dibuat_pada DESC);
CREATE INDEX IF NOT EXISTS idx_otp_phone_created     ON public.otp_codes(phone, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_percakapan_profil     ON public.percakapan(profil_id, diperbarui_pada DESC);
CREATE INDEX IF NOT EXISTS idx_pesan_percakapan      ON public.pesan_chat(percakapan_id, dibuat_pada);

-- ----------------------------------------------------------------------------
-- ROW LEVEL SECURITY (RLS) & ACCESS CONTROL
-- ----------------------------------------------------------------------------
ALTER TABLE public.profil_keluarga   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kebutuhan_gizi    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bahan_pangan      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pengaturan_rumus  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.panen             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.riwayat_keputusan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.otp_codes         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.percakapan        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pesan_chat        ENABLE ROW LEVEL SECURITY;

-- 1. Profil Keluarga: Hanya pemilik akun yang berhak akses penuh
DROP POLICY IF EXISTS profil_own ON public.profil_keluarga;
CREATE POLICY profil_own ON public.profil_keluarga
FOR ALL TO authenticated
USING (user_id = (SELECT auth.uid()))
WITH CHECK (user_id = (SELECT auth.uid()));

-- 2. Kebutuhan Gizi: Terbuka untuk umum (read-only)
DROP POLICY IF EXISTS kebutuhan_baca ON public.kebutuhan_gizi;
CREATE POLICY kebutuhan_baca ON public.kebutuhan_gizi
FOR SELECT TO anon, authenticated
USING (TRUE);

-- 3. Bahan Pangan: Dapat dibaca publik; update harga terbatas pada user login
DROP POLICY IF EXISTS bahan_baca ON public.bahan_pangan;
CREATE POLICY bahan_baca ON public.bahan_pangan
FOR SELECT TO anon, authenticated
USING (TRUE);

DROP POLICY IF EXISTS bahan_ubah_harga ON public.bahan_pangan;
CREATE POLICY bahan_ubah_harga ON public.bahan_pangan
FOR UPDATE TO authenticated
USING (TRUE)
WITH CHECK (TRUE);

REVOKE UPDATE ON public.bahan_pangan FROM authenticated;
GRANT UPDATE (harga_umum_per_kg, harga_diperbarui_pada)
    ON public.bahan_pangan TO authenticated;

-- 4. Pengaturan Rumus: Publik hanya melihat yang disahkan, authenticated melihat semua
DROP POLICY IF EXISTS rumus_baca ON public.pengaturan_rumus;
CREATE POLICY rumus_baca ON public.pengaturan_rumus
FOR SELECT TO anon, authenticated
USING (
    status_pengesahan = 'disahkan'
    OR (SELECT auth.role()) = 'authenticated'
);

-- 5. Panen & Riwayat: Terisolasi ketat per profil pengguna
DROP POLICY IF EXISTS panen_own ON public.panen;
CREATE POLICY panen_own ON public.panen
FOR ALL TO authenticated
USING (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
))
WITH CHECK (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
));

DROP POLICY IF EXISTS riwayat_own ON public.riwayat_keputusan;
CREATE POLICY riwayat_own ON public.riwayat_keputusan
FOR ALL TO authenticated
USING (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
))
WITH CHECK (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
));

-- 6. Percakapan & Pesan Bu Nita AI: Terisolasi per profil keluarga
DROP POLICY IF EXISTS percakapan_own ON public.percakapan;
CREATE POLICY percakapan_own ON public.percakapan
FOR ALL TO authenticated
USING (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
))
WITH CHECK (profil_id IN (
    SELECT id FROM public.profil_keluarga WHERE user_id = (SELECT auth.uid())
));

DROP POLICY IF EXISTS pesan_own ON public.pesan_chat;
CREATE POLICY pesan_own ON public.pesan_chat
FOR ALL TO authenticated
USING (percakapan_id IN (
    SELECT c.id
    FROM public.percakapan c
    JOIN public.profil_keluarga p ON p.id = c.profil_id
    WHERE p.user_id = (SELECT auth.uid())
))
WITH CHECK (percakapan_id IN (
    SELECT c.id
    FROM public.percakapan c
    JOIN public.profil_keluarga p ON p.id = c.profil_id
    WHERE p.user_id = (SELECT auth.uid())
));

-- Catatan untuk otp_codes: Tidak ada policy SELECT/INSERT untuk anon/authenticated
-- sehingga kunci API client Supabase tidak bisa membacanya. Akses hanya melalui
-- backend Route Handler menggunakan direct PostgreSQL pool connection.

-- ----------------------------------------------------------------------------
-- SUPABASE STORAGE BUCKET: hasil-panen
-- ----------------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('hasil-panen', 'hasil-panen', FALSE)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS foto_insert_own ON storage.objects;
CREATE POLICY foto_insert_own ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (
    bucket_id = 'hasil-panen'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
);

DROP POLICY IF EXISTS foto_select_own ON storage.objects;
CREATE POLICY foto_select_own ON storage.objects
FOR SELECT TO authenticated
USING (
    bucket_id = 'hasil-panen'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
);

DROP POLICY IF EXISTS foto_delete_own ON storage.objects;
CREATE POLICY foto_delete_own ON storage.objects
FOR DELETE TO authenticated
USING (
    bucket_id = 'hasil-panen'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
);

COMMIT;

